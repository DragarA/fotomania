import { useQuery } from '@tanstack/react-query';
import { createFileRoute } from '@tanstack/react-router';

export const Route = createFileRoute('/')({
  component: HomeComponent,
});

function HomeComponent() {
  // Example: This will use the SDK once it's generated
  // For now, we'll use a simple fetch
  const { data, isLoading, error } = useQuery({
    queryKey: ['health'],
    queryFn: async () => {
      const response = await fetch('http://localhost:3000/health');
      if (!response.ok) {
        throw new Error('Network response was not ok');
      }
      return response.json();
    },
  });

  return (
    <div>
      <h1>Welcome to Fotomania!</h1>
      <p>This is a Turborepo monorepo with:</p>
      <ul>
        <li>NestJS API with OpenAPI</li>
        <li>React + Vite Frontend</li>
        <li>TanStack Query for data fetching</li>
        <li>TanStack Router for routing</li>
        <li>Autogenerated SDK from OpenAPI spec</li>
      </ul>

      <div style={{ marginTop: '2rem' }}>
        <h2>API Health Check</h2>
        {isLoading && <p>Loading...</p>}
        {error && <p>Error: {error.message}</p>}
        {data && (
          <pre style={{ background: '#f5f5f5', padding: '1rem' }}>
            {JSON.stringify(data, null, 2)}
          </pre>
        )}
      </div>
    </div>
  );
}
